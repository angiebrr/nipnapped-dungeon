//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

Engine engine(SCREEN_WIDTH, SCREEN_HEIGHT);

int main() 
{
    engine.load();
    
    while ( !TCODConsole::isWindowClosed() ) 
    {
        engine.update();
        engine.render();
        TCODConsole::flush();
    }
    
    engine.save();
    
    return 0;
}

