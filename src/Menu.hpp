class Menu 
{
    public:
        enum MenuItemCode 
        {
            NONE, // Close game window
            NEW_GAME, // Load a new game
            CONTINUE, // Load a previous game
            EXIT // Exit game
        };
        
        ~Menu();
        void clear();
        void addItem(MenuItemCode code, const char *label);
        MenuItemCode pick();
        
    protected:
        struct MenuItem 
        {
            MenuItemCode code;
            const char* label;
        };
        
        TCODList<MenuItem*> items;
};

