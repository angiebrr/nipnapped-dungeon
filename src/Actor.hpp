//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Actor 
{
    public:
        int x, y; // Position on map
        int code; // ASCII Code
        TCODColor color; // ASCII Color
        const char* name; // The actor's name
 
        Actor(int x, int y, int code, const char* name, const TCODColor& color);
        void render() const;
        void update();
        bool moveOrAttack(int x, int y);
};

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#endif // ACTOR_HPP